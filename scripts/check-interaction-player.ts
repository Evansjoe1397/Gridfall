import assert from 'node:assert/strict';
import { applyCommand, createInitialState, type GameState } from '../shared/game.ts';
import { interactionPlayer } from '../src/interaction-player.ts';

const initial = createInitialState();
initial.objects = [];
initial.players.P1.position = { x: 2, y: 2 };
initial.players.P2.position = { x: 3, y: 2 };
initial.players.P1.hand = [{ instanceId: 'attack', cardId: 'attack-3' }];
initial.players.P2.hand = [{ instanceId: 'defend', cardId: 'defend-2' }];
assert.equal(interactionPlayer(initial), 'P1');
const attack = applyCommand(initial, { type: 'attack', playerId: 'P1', cardInstanceId: 'attack', targetId: 'P2' });
assert.ok(attack.ok);
if (!attack.ok) throw new Error(attack.error);
assert.equal(attack.state.activePlayerId, 'P1');
assert.equal(attack.state.phase, 'defending');
assert.equal(interactionPlayer(attack.state), 'P2', 'The defender must retain control during the attacker’s turn.');

const state = structuredClone(initial);
state.phase = 'choosing-force-disarm-discard';
state.forceDisarm = { targetId: 'P2' };
assert.equal(interactionPlayer(state), 'P2', 'Only the target receives the forced discard instruction.');
state.phase = 'choosing-mind-tricks-enemy-discard';
state.mindTricks = { casterId: 'P1', enemyId: 'P2', level: 3, maxDiscards: 1, discarded: 1, revealedInstanceIds: [], enemyDiscardsRemaining: 1, undo: null };
assert.equal(interactionPlayer(state), 'P2');
state.phase = 'choosing-mind-tricks-discard';
assert.equal(interactionPlayer(state), 'P1', 'Mind Tricks switches control between caster and target.');
state.phase = 'choosing-grimoire-discard';
state.pendingAttack = attack.state.pendingAttack;
assert.equal(interactionPlayer(state), 'P2');
state.phase = 'choosing-end-discard';
assert.equal(interactionPlayer(state), 'P1');
state.phase = 'choosing-focus-card';
(state as GameState & { openingSetup: { pendingPlayerIds: string[] } }).openingSetup = { pendingPlayerIds: ['P2'] };
assert.equal(interactionPlayer(state), 'P2');
state.phase = 'active';
state.activePlayerId = 'P2';
assert.equal(interactionPlayer(state), 'P2', 'Turn ownership updates when the turn passes.');
console.log('Interaction ownership checks passed: turn changes, defense, forced discards, Mind Tricks and opening selection.');
